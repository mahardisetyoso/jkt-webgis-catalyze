// Generates simple original SVG placeholder cards for each district (no third-
// party imagery, so no licensing). Swap these for CC-BY photos at the same paths
// when desired. Run: npm run data:images
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const OUT_DIR = resolve("public/images");

const DISTRICTS = [
  { file: "jakpus-sudirman.svg", name: "Jakarta Pusat", theme: "Jantung Bisnis", highlights: "Sudirman · SCBD", color: "#1565c0" },
  { file: "jakbar-untar.svg", name: "Jakarta Barat", theme: "Kampus & Kuliner", highlights: "Trisakti · Untar · Ciputra · Tanjung Duren", color: "#6a1b9a" },
  { file: "jaksel-blokm.svg", name: "Jakarta Selatan", theme: "Pop Culture & Hiburan", highlights: "Blok M · Kemang", color: "#ad1457" },
  { file: "jakut-pik.svg", name: "Jakarta Utara", theme: "Perdagangan & Pecinan", highlights: "PIK · Glodok", color: "#00695c" },
  { file: "jaktim-pulogadung.svg", name: "Jakarta Timur", theme: "Industri Manufaktur", highlights: "Pulogadung", color: "#4e342e" },
];

const esc = (s) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function svg({ name, theme, highlights, color }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 800" font-family="Segoe UI, system-ui, sans-serif">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${color}"/>
      <stop offset="1" stop-color="#101828"/>
    </linearGradient>
  </defs>
  <rect width="1200" height="800" fill="url(#g)"/>
  <g fill="#ffffff" opacity="0.08">
    <circle cx="1000" cy="160" r="220"/>
    <circle cx="180" cy="680" r="160"/>
  </g>
  <text x="80" y="120" fill="#ffffff" opacity="0.75" font-size="30" letter-spacing="6">DKI JAKARTA</text>
  <text x="80" y="360" fill="#ffffff" font-size="96" font-weight="700">${esc(name)}</text>
  <text x="80" y="440" fill="#ffffff" opacity="0.92" font-size="48" font-weight="500">${esc(theme)}</text>
  <rect x="80" y="620" width="${Math.min(1040, 60 + highlights.length * 17)}" height="4" fill="#ffffff" opacity="0.5"/>
  <text x="80" y="690" fill="#ffffff" opacity="0.88" font-size="34">${esc(highlights)}</text>
</svg>
`;
}

mkdirSync(OUT_DIR, { recursive: true });
for (const d of DISTRICTS) {
  writeFileSync(resolve(OUT_DIR, d.file), svg(d));
}

const credits = `# Image credits

The five district images in this folder are **original placeholder graphics**
generated by \`scripts/build-images.mjs\` (run \`npm run data:images\`). They contain
no third-party imagery and carry no license restriction (treat as CC0 / public
domain). Swap them for CC-BY photographs at the same file paths when desired.

${DISTRICTS.map((d) => `- \`${d.file}\` — ${d.name} (${d.theme})`).join("\n")}
`;
writeFileSync(resolve(OUT_DIR, "CREDITS.md"), credits);

console.log(`wrote ${DISTRICTS.length} SVG placeholders + CREDITS.md -> ${OUT_DIR}`);
